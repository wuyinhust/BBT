/// The reference used for growth curves and percentile assessments. Persisted
/// measurements stay in cm/kg, so changing this value only changes the
/// comparison curve and never rewrites historical records.
enum GrowthReferenceStandard: String, CaseIterable, Identifiable {
    case who2006
    case chinaNHC2022

    var id: String { rawValue }

    var title: String {
        switch self {
        case .who2006: return "WHO 2006 儿童生长标准"
        case .chinaNHC2022: return "国家卫健委《7岁以下儿童生长标准》"
        }
    }

    var shortTitle: String {
        switch self {
        case .who2006: return "WHO 2006"
        case .chinaNHC2022: return "国家卫健委"
        }
    }

    var supportedAgeText: String {
        switch self {
        case .who2006: return "0–5岁"
        case .chinaNHC2022: return "0–7岁"
        }
    }
}

/// Keeps the automatic default separate from an explicit choice. This lets a
/// traveller receive the correct first-run default without overriding a choice
/// they already made in Settings.
enum GrowthStandardPreference: String, CaseIterable, Identifiable {
    case automatic
    case who2006
    case chinaNHC2022

    static let storageKey = "growth_reference_standard_preference_v1"
    static let defaults = MeasurementSystemPreference.defaults

    var id: String { rawValue }

    var title: String {
        switch self {
        case .automatic:
            return "跟随当前地区（\(Self.defaultStandard.shortTitle)）"
        case .who2006:
            return GrowthReferenceStandard.who2006.title
        case .chinaNHC2022:
            return GrowthReferenceStandard.chinaNHC2022.title
        }
    }

    var resolvedStandard: GrowthReferenceStandard {
        switch self {
        case .automatic: return Self.defaultStandard
        case .who2006: return .who2006
        case .chinaNHC2022: return .chinaNHC2022
        }
    }

    static var current: GrowthStandardPreference {
        guard let rawValue = defaults.string(forKey: storageKey),
              let preference = GrowthStandardPreference(rawValue: rawValue) else {
            return .automatic
        }
        return preference
    }

    static var currentStandard: GrowthReferenceStandard {
        current.resolvedStandard
    }

    /// China is selected for a China region or the canonical Beijing IANA zone.
    /// Simplified Chinese is intentionally only a fallback when iOS does not
    /// provide a region: many overseas users use a Chinese app language.
    static var defaultStandard: GrowthReferenceStandard {
        let locale = Locale.autoupdatingCurrent
        let timeZone = TimeZone.autoupdatingCurrent
        let region = locale.region?.identifier.uppercased()
        let isBeijingTime = timeZone.identifier == "Asia/Shanghai"

        if region == "CN" || isBeijingTime {
            return .chinaNHC2022
        }

        let isUTCPlusEight = timeZone.secondsFromGMT() == 8 * 60 * 60
        let language = locale.language.languageCode?.identifier.lowercased()
        if region == nil, isUTCPlusEight, language == "zh", AppLanguage.current == .simplifiedChinese {
            return .chinaNHC2022
        }

        return .who2006
    }
}

