/// Offline tables from WS/T 423-2022, Appendix B, tables B.1-B.4.
/// Published values are at whole months until age 2 and every three months
/// thereafter; the app linearly interpolates between adjacent published rows.
private enum NHCGrowthStandard {
    private static let daysPerMonth = 30.4375
    static let supportedAgeDays = 0.0...(84.0 * daysPerMonth)

    static func assessment(kind: GrowthMetricKind, gender: BabyGender, ageDays: Double, value: Double) -> WHOGrowthAssessment? {
        guard let row = row(kind: kind, gender: gender, ageDays: ageDays), value > 0 else { return nil }
        let zScore = zScore(for: value, in: row.values)
        let percentile = 0.5 * (1 + erf(zScore / sqrt(2))) * 100
        return WHOGrowthAssessment(percentile: min(max(percentile, 0.1), 99.9), zScore: zScore)
    }

    static func value(kind: GrowthMetricKind, gender: BabyGender, ageDays: Double, zScore: Double) -> Double? {
        guard let row = row(kind: kind, gender: gender, ageDays: ageDays) else { return nil }
        return value(for: zScore, in: row.values)
    }

    private static func row(kind: GrowthMetricKind, gender: BabyGender, ageDays: Double) -> NHCGrowthSDRow? {
        guard supportedAgeDays.contains(ageDays) else { return nil }
        let table: [NHCGrowthSDRow]
        switch (kind, gender) {
        case (.weight, .girl): table = weightGirls
        case (.weight, .boy): table = weightBoys
        case (.height, .girl): table = heightGirls
        case (.height, .boy): table = heightBoys
        }

        let upperIndex = table.firstIndex { $0.ageDays >= ageDays } ?? (table.count - 1)
        let lowerIndex = max(upperIndex - 1, 0)
        let lower = table[lowerIndex]
        let upper = table[upperIndex]
        let interval = max(upper.ageDays - lower.ageDays, 1)
        let fraction = min(max((ageDays - lower.ageDays) / interval, 0), 1)
        return NHCGrowthSDRow(
            ageDays: ageDays,
            values: zip(lower.values, upper.values).map { pair in
                pair.0 + (pair.1 - pair.0) * fraction
            }
        )
    }

    private static func zScore(for value: Double, in values: [Double]) -> Double {
        guard values.count == 7 else { return 0 }
        if value <= values[0] {
            return -3 + (value - values[0]) / max(values[1] - values[0], 0.01)
        }
        if value >= values[6] {
            return 3 + (value - values[6]) / max(values[6] - values[5], 0.01)
        }
        let upperIndex = values.firstIndex { $0 >= value } ?? 6
        let lowerIndex = max(upperIndex - 1, 0)
        let fraction = (value - values[lowerIndex]) / max(values[upperIndex] - values[lowerIndex], 0.01)
        return Double(lowerIndex - 3) + fraction
    }

    private static func value(for zScore: Double, in values: [Double]) -> Double? {
        guard values.count == 7 else { return nil }
        let clamped = min(max(zScore, -3), 3)
        let shifted = clamped + 3
        let lowerIndex = min(max(Int(floor(shifted)), 0), 6)
        let upperIndex = min(lowerIndex + 1, 6)
        let fraction = shifted - Double(lowerIndex)
        return values[lowerIndex] + (values[upperIndex] - values[lowerIndex]) * fraction
    }

    private static func rows(_ raw: String) -> [NHCGrowthSDRow] {
        let ages = Array(0...23).map { Double($0) }
            + Array(stride(from: 24.0, through: 81.0, by: 3.0))
        let measurements = raw
            .split(whereSeparator: { $0.isNewline })
            .map { $0.split(separator: ",").compactMap { Double($0) } }
            .filter { $0.count == 7 }
        precondition(measurements.count == ages.count, "WS/T 423-2022 table row count mismatch")
        return zip(ages, measurements).map { month, values in
            NHCGrowthSDRow(ageDays: month * daysPerMonth, values: values)
        }
    }

