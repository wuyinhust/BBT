import Foundation
import Darwin

struct WHOGrowthLMS: Hashable {
    let ageDays: Double
    let l: Double
    let m: Double
    let s: Double
}

struct WHOGrowthAssessment: Hashable {
    let percentile: Double
    let zScore: Double

    var percentileText: String {
        if percentile < 1 { return "低于 P1" }
        if percentile > 99 { return "高于 P99" }
        return "P\(Int(percentile.rounded()))"
    }
}

/// Offline LMS tables from the WHO Child Growth Standards (0-5 years).
/// Sources:
/// https://www.who.int/tools/child-growth-standards/standards/weight-for-age
/// https://www.who.int/tools/child-growth-standards/standards/length-height-for-age
enum WHOGrowthStandard {
    static let supportedAgeDays = 0.0...1826.0
    static let curvePercentiles: [(label: String, percentile: Double, z: Double)] = [
        ("P3", 3, -1.880793608),
        ("P15", 15, -1.036433389),
        ("P50", 50, 0),
        ("P85", 85, 1.036433389),
        ("P97", 97, 1.880793608)
    ]

    static func assessment(kind: GrowthMetricKind, gender: BabyGender, ageDays: Double, value: Double) -> WHOGrowthAssessment? {
        guard let row = row(kind: kind, gender: gender, ageDays: ageDays), value > 0 else { return nil }
        let z: Double
        if abs(row.l) < 0.000_001 {
            z = log(value / row.m) / row.s
        } else {
            z = (pow(value / row.m, row.l) - 1) / (row.l * row.s)
        }
        let percentile = 0.5 * (1 + erf(z / sqrt(2))) * 100
        return WHOGrowthAssessment(percentile: min(max(percentile, 0.1), 99.9), zScore: z)
    }

    static func value(kind: GrowthMetricKind, gender: BabyGender, ageDays: Double, zScore: Double) -> Double? {
        guard let row = row(kind: kind, gender: gender, ageDays: ageDays) else { return nil }
        if abs(row.l) < 0.000_001 {
            return row.m * exp(row.s * zScore)
        }
        let base = 1 + row.l * row.s * zScore
        guard base > 0 else { return nil }
        return row.m * pow(base, 1 / row.l)
    }

    static func row(kind: GrowthMetricKind, gender: BabyGender, ageDays: Double) -> WHOGrowthLMS? {
        guard supportedAgeDays.contains(ageDays) else { return nil }
        let table: [WHOGrowthLMS]
        switch (kind, gender) {
        case (.weight, .girl): table = weightGirls
        case (.weight, .boy): table = weightBoys
        case (.height, .girl): table = heightGirls
        case (.height, .boy): table = heightBoys
        }
        let upperIndex = table.firstIndex { $0.ageDays >= ageDays } ?? (table.count - 1)
        let lowerIndex = max(upperIndex - 1, 0)
        let lower = table[lowerIndex]
        let upper = table[upperIndex]
        let interval = upper.ageDays - lower.ageDays
        let fraction = interval > 0 ? min(max((ageDays - lower.ageDays) / interval, 0), 1) : 0
        return WHOGrowthLMS(
            ageDays: ageDays,
            l: lower.l + (upper.l - lower.l) * fraction,
            m: lower.m + (upper.m - lower.m) * fraction,
            s: lower.s + (upper.s - lower.s) * fraction
        )
    }

    private static func make(_ rows: [(Double, Double, Double, Double)]) -> [WHOGrowthLMS] {
        rows.map { WHOGrowthLMS(ageDays: $0.0, l: $0.1, m: $0.2, s: $0.3) }
    }

